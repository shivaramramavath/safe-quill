import { Injectable } from '@nestjs/common';
import { ExportResponse } from '@safe-quill/shared';

@Injectable()
export class ExportService {
  exportTxt(
    subject: string,
    body: string,
    score?: number,
    level?: string,
  ): ExportResponse {
    const lines = [
      '====================================================',
      'SAFEQUILL EMAIL EXPORT',
      '====================================================',
      `Subject: ${subject || '(No Subject)'}`,
      `Date:    ${new Date().toUTCString()}`,
    ];

    if (score !== undefined && level) {
      lines.push(`Verdict: ${level} (${score}/100 Risk Score)`);
    }

    lines.push(
      '----------------------------------------------------',
      '',
      body || '',
      '',
      '====================================================',
      'Generated by SafeQuill - Anti-Phishing & Security',
    );

    const safeTitle = (subject || 'email-draft')
      .toLowerCase()
      .replace(/[^a-z0-9_-]/g, '_')
      .slice(0, 30);

    return {
      format: 'txt',
      filename: `${safeTitle}.txt`,
      contentType: 'text/plain; charset=utf-8',
      content: lines.join('\n'),
    };
  }

  exportEml(
    subject: string,
    body: string,
    from?: string,
    to?: string,
    rawHeaders?: string,
  ): ExportResponse {
    const sender = from || 'user@safequill.local';
    const recipient = to || 'recipient@example.com';
    const dateStr = new Date().toUTCString();
    const messageId = `<${Date.now()}.${Math.random().toString(36).substring(2, 9)}@safequill.local>`;

    let headers = [
      `From: ${sender}`,
      `To: ${recipient}`,
      `Subject: ${subject || 'Untitled Draft'}`,
      `Date: ${dateStr}`,
      `Message-ID: ${messageId}`,
      'MIME-Version: 1.0',
      'Content-Type: text/plain; charset=utf-8',
      'Content-Transfer-Encoding: 8bit',
      'X-Mailer: SafeQuill AI Security 2.0',
    ];

    if (rawHeaders) {
      // Append any custom provided headers
      headers.push(rawHeaders);
    }

    const emlContent = `${headers.join('\r\n')}\r\n\r\n${body || ''}\r\n`;

    const safeTitle = (subject || 'email')
      .toLowerCase()
      .replace(/[^a-z0-9_-]/g, '_')
      .slice(0, 30);

    return {
      format: 'eml',
      filename: `${safeTitle}.eml`,
      contentType: 'message/rfc822',
      content: emlContent,
    };
  }

  exportJson(data: any): ExportResponse {
    return {
      format: 'json',
      filename: `safequill-audit-${Date.now()}.json`,
      contentType: 'application/json',
      content: JSON.stringify(data, null, 2),
    };
  }
}
